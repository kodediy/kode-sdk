#!/usr/bin/env python3
"""core/assets/tokens.json into core/include/kui_tokens.h and kode/internal/include/kode_colors.h.

    tools/gen_tokens.py           write both headers
    tools/gen_tokens.py --check   exit 1 when a header on disk is not what tokens.json says

kui_tokens.h is the kit's; kode_colors.h gives the standard layer the palette by
name. Both are checked in, so building never needs Python; CI runs --check so
they cannot drift.
"""
import argparse
import json
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
SRC = KIT / "core" / "assets" / "tokens.json"
OUT = KIT / "core" / "include" / "kui_tokens.h"
COLORS_OUT = KIT.parent / "kode" / "internal" / "include" / "kode_colors.h"
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
NAME = re.compile(r"^[a-z][a-z0-9_]*$")

# The standard layer's name for each palette entry: KODE_<name> in kode_colors.h.
# Every palette entry is named here and every name here is a palette entry;
# load() fails on the first that is not, so the two cannot drift apart.
COLOR_NAMES = {
    "page":         "BLACK",
    "soft_black":   "SOFT_BLACK",
    "light_grey":   "LIGHT_GREY",
    "medium_grey":  "GREY",
    "bold_yellow":  "YELLOW",
    "kody_blue":    "BLUE",
    "row_dark":     "DARK_GREY",
    "off_grey":     "CHARCOAL",
    "rest_grey":    "WARM_GREY",
    "ok_green":     "GREEN",
    "charge_green": "LIGHT_GREEN",
    "danger_red":   "DEEP_RED",
}

# The colours that are not tokens, written after the palette: white, which the
# brand's palette lacks, and the six pure colours the status LED needs. A pure
# name must not collide with a token's KODE_ name; a pure VALUE equal to a
# token's is allowed.
WHITE = ("WHITE", "0xFFFFFFU", "White; not a palette token")
PURE = [
    ("RED",         "0xFF0000U", "Pure red, for the LED; not a palette token"),
    ("MAGENTA",     "0xFF00FFU", "Pure magenta, for the LED; not a palette token"),
    ("CYAN",        "0x00FFFFU", "Pure cyan, for the LED; not a palette token"),
    ("PURE_GREEN",  "0x00FF00U", "Pure green, for the LED; not a palette token"),
    ("PURE_BLUE",   "0x0000FFU", "Pure blue, for the LED; not a palette token"),
    ("PURE_YELLOW", "0xFFFF00U", "Pure yellow, for the LED; not a palette token"),
]
NON_TOKEN = [WHITE] + PURE

COLORS_PREAMBLE = """/* SPDX-License-Identifier: GPL-3.0-or-later */
/**
 * @file kode_colors.h
 * @brief The Kode palette by name, for the standard layer; an app gets it through kode.h.
 *
 * Generated by components/kui/tools/gen_tokens.py from tokens.json. Do not edit.
 */
#ifndef KODE_COLORS_H_
#define KODE_COLORS_H_

#ifndef KODE_H_
#error "kode_colors.h is part of kode.h: include kode.h"
#endif

#include <stdint.h>

/** @brief A colour as 0xRRGGBB: red in the top byte, blue in the bottom. */
typedef uint32_t kode_color_t;
"""

PREAMBLE = """/* SPDX-License-Identifier: GPL-3.0-or-later */
/**
 * @file kui_tokens.h
 * @brief The kit's design tokens: palette, style roles, sizes and opacities.
 *
 * Generated by tools/gen_tokens.py from tokens.json. Do not edit.
 */
#ifndef KUI_TOKENS_H
#define KUI_TOKENS_H
"""


def fail(msg):
    sys.exit(f"gen_tokens: {msg}")


def load():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    palette = {}
    for p in data["palette"]:
        if not NAME.match(p["name"]):
            fail(f"palette name {p['name']!r} is not lower_snake_case")
        if p["name"] in palette:
            fail(f"palette name {p['name']!r} appears twice")
        if not HEX.match(p["value"]):
            fail(f"palette {p['name']}: {p['value']!r} is not #RRGGBB")
        palette[p["name"]] = p
    seen = set()
    for block in ("roles", "sizes", "opacities"):
        for t in data[block]:
            if not NAME.match(t["name"]) or t["name"] in seen:
                fail(f"{block}: {t['name']!r} is not a new lower_snake_case name")
            seen.add(t["name"])
    for token in COLOR_NAMES:
        if token not in palette:
            fail(f"COLOR_NAMES names {token!r}, which the palette lacks")
    for token in palette:
        if token not in COLOR_NAMES:
            fail(f"palette entry {token!r} has no KODE_ name: add it to COLOR_NAMES")
    names = list(COLOR_NAMES.values()) + [n[0] for n in NON_TOKEN]
    if len(set(names)) != len(names):
        fail("COLOR_NAMES gives two colours one KODE_ name")
    for r in data["roles"]:
        if r["palette"] not in palette:
            fail(f"role {r['name']} names {r['palette']!r}, which the palette lacks")
    for o in data["opacities"]:
        if not 0 <= o["percent"] <= 100:
            fail(f"opacity {o['name']}: {o['percent']} is not a percentage")
    return data


def block(title, rows):
    """rows: (macro, value, comment) -> aligned #defines under a title."""
    width = max(len(m) for m, _, _ in rows)
    vwidth = max(len(v) for _, v, _ in rows)
    out = ["", f"/* {title} */"]
    for macro, value, comment in rows:
        out.append(f"#define {macro.ljust(width)} {value.ljust(vwidth)} /**< {comment} */")
    return out


def header(data):
    lines = PREAMBLE.rstrip("\n").split("\n")
    lines += block("The palette, 0xRRGGBB.", [
        (f"KUI_PALETTE_{p['name'].upper()}", f"0x{p['value'][1:].upper()}U", p["help"])
        for p in data["palette"]])
    lines += block("The roles the styles name.", [
        (f"KUI_COLOR_{r['name'].upper()}", f"lv_color_hex(KUI_PALETTE_{r['palette'].upper()})", r["help"])
        for r in data["roles"]])
    lines += block("Sizes, in pixels of the 410 x 502 glass.", [
        (f"KUI_{s['name'].upper()}", str(s["value"]), s["help"]) for s in data["sizes"]])
    lines += block("Opacities.", [
        (f"KUI_OPA_{o['name'].upper()}", f"((lv_opa_t){(255 * o['percent']) // 100}U)",
         f"{o['percent']} %: {o['help']}") for o in data["opacities"]])
    lines += ["", "#endif /* KUI_TOKENS_H */", ""]
    return "\n".join(lines)


def colors_header(data):
    lines = COLORS_PREAMBLE.rstrip("\n").split("\n")
    rows = [(f"KODE_{COLOR_NAMES[p['name']]}", f"0x{p['value'][1:].upper()}U", p["help"])
            for p in data["palette"]]
    rows += [(f"KODE_{n[0]}", n[1], n[2]) for n in NON_TOKEN]
    lines += block("The palette, 0xRRGGBB. Any other colour is kode_rgb(r, g, b).", rows)
    lines += ["", "#endif /* KODE_COLORS_H_ */", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    data = load()
    outputs = [(OUT, header(data)), (COLORS_OUT, colors_header(data))]
    if ap.parse_args().check:
        stale = False
        for path, text in outputs:
            rel = path.relative_to(KIT.parent)
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{rel} is stale: run tools/gen_tokens.py")
                stale = True
            else:
                print(f"{rel} matches tokens.json")
        return 1 if stale else 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(KIT.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
