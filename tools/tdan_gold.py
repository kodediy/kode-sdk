#!/usr/bin/env python3
"""The screen analysis' golden data.

    tools/tdan_gold.py header DIR [-o FILE] [--date TEXT]
        Writes tdan_gold.h from the golden photos in DIR and H.txt, the panel ->
        photo homography as nine numbers. The photos are the station's export,
        blanco.raw565 and gris.raw565 ("W H" on a line, then the pixels, RGB565
        little endian), or else white.png and grey.png. The table is the zone
        cells of each, computed by the analysis itself (tdan_zone_cells), built
        with the host's C compiler.

    tools/tdan_gold.py frames DIR
        Writes the host suite's frames: a good panel photographed through the
        nominal pose (black with marks, white, grey, red, green, blue), the same
        white and grey with a cluster of dead pixels, and a black with no marks.

Standard library and Pillow only.
"""
import argparse
import os
import random
import shutil
import subprocess
import sys
import tempfile

from PIL import Image, ImageFilter

SDK = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
ANALYSIS = os.path.join(SDK, "components", "kaos", "test_dot", "analysis")
HEADER = os.path.join(ANALYSIS, "src", "tdan_gold.h")

# The photo the station takes: the sensor window and the nominal pose of the
# screen in it (panel -> photo), measured on the printed fixture on 28-oct-2026.
WIN_W, WIN_H = 1056, 768
H_NOMINAL = (2.13662459, 0.0277076, 90.13618311,
             -0.00851681, 2.09238792, -147.4912306,
             6.212e-05, -1.692e-05, 1.0)
PANEL_W, PANEL_H = 410, 502
MARKS = ((42, 167), (368, 167), (368, 338), (42, 338))   # the marks pattern's squares, 24 px
MARK_HALF = 12
ZR, ZC = 25, 41

CELLS_MAIN = r"""
#include <stdio.h>
#include <stdlib.h>
#include "tdan.h"
int main(int argc, char **argv)
{
    int32_t w = atoi(argv[2]), h = atoi(argv[3]);
    tdan_h_t hm;
    for (int i = 0; i < 9; i++) { hm.h[i] = atof(argv[4 + i]); }
    FILE *f = fopen(argv[1], "rb");
    uint16_t *px = malloc((size_t)w * (size_t)h * 2U);
    uint8_t *l = malloc((size_t)w * (size_t)h);
    if ((f == NULL) || (fread(px, 2, (size_t)w * (size_t)h, f) != (size_t)w * (size_t)h)) { return 2; }
    fclose(f);
    tdan_luma(px, w, h, l);
    tdan_work_t wk = { 0 };
    wk.a = malloc(TDAN_PLANE_FLOATS * sizeof(float)); wk.b = malloc(TDAN_PLANE_FLOATS * sizeof(float));
    wk.c = malloc(TDAN_PLANE_FLOATS * sizeof(float)); wk.d = malloc(TDAN_PLANE_FLOATS * sizeof(float));
    uint8_t cells[TDAN_ZR][TDAN_ZC];
    tdan_zone_cells(l, w, h, &hm, &wk, cells);
    for (int y = 0; y < TDAN_ZR; y++) {
        for (int x = 0; x < TDAN_ZC; x++) { printf("%d%s", cells[y][x], (x + 1 < TDAN_ZC) ? " " : "\n"); }
    }
    return 0;
}
"""


def rgb565_bytes(img):
    """The photo as the camera delivers it: RGB565, little endian."""
    rgb = img.convert("RGB").tobytes()
    out = bytearray(len(rgb) // 3 * 2)
    for n in range(len(rgb) // 3):
        r, g, b = rgb[3 * n], rgb[3 * n + 1], rgb[3 * n + 2]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        out[2 * n] = v & 0xFF
        out[2 * n + 1] = v >> 8
    return bytes(out)


def read_photo(dirname, raw, png):
    """A golden photo as (width, height, RGB565 bytes): the station's raw565 export, else a PNG."""
    path = os.path.join(dirname, raw)
    if os.path.exists(path):
        with open(path, "rb") as f:
            w, h = (int(v) for v in f.readline().split())
            return w, h, f.read(w * h * 2)
    img = Image.open(os.path.join(dirname, png))
    return img.width, img.height, rgb565_bytes(img)


def read_h(path):
    with open(path) as f:
        h = [float(x) for x in f.read().split()]
    if len(h) != 9:
        sys.exit(f"{path}: nine numbers expected")
    return h


def cells_of(tool, photo, h):
    w, ht, pixels = photo
    with tempfile.NamedTemporaryFile(suffix=".raw565", delete=False) as t:
        t.write(pixels)
        raw = t.name
    try:
        out = subprocess.run([tool, raw, str(w), str(ht)] + [repr(x) for x in h],
                             capture_output=True, text=True, check=True).stdout
    finally:
        os.unlink(raw)
    return [[int(v) for v in line.split()] for line in out.splitlines()]


def format_header(white, grey, date):
    def table(name, rows):
        body = ",\n".join("{" + ",".join(str(v) for v in row) + "}" for row in rows)
        return f"static const uint8_t {name}[TDAN_ZR][TDAN_ZC] = {{\n{body}\n}};\n"
    return ("/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
            "/**\n"
            " * @file tdan_gold.h\n"
            " * @brief The golden photos' zone cells: each cell's mean over the median of the cells, x100.\n"
            " *\n"
            f" * Generated by tools/tdan_gold.py from the golden photos taken on {date}. Do not edit.\n"
            " */\n"
            "#ifndef TDAN_GOLD_H_\n#define TDAN_GOLD_H_\n\n#include <stdint.h>\n\n#include \"tdan.h\"\n\n"
            "/** @brief The white screen's cells. */\n" + table("TDAN_GOLD_WHITE", white) + "\n"
            "/** @brief The grey screen's cells. */\n" + table("TDAN_GOLD_GREY", grey) + "\n"
            "#endif /* TDAN_GOLD_H_ */\n")


def cmd_header(args):
    cc = shutil.which(os.environ.get("CC", "cc"))
    if cc is None:
        sys.exit("no C compiler on the PATH")
    h = read_h(os.path.join(args.dir, "H.txt"))
    with tempfile.TemporaryDirectory() as tmp:
        main = os.path.join(tmp, "cells.c")
        tool = os.path.join(tmp, "cells")
        with open(main, "w") as f:
            f.write(CELLS_MAIN)
        src = [os.path.join(ANALYSIS, "src", n) for n in ("tdan_geom.c", "tdan_pix.c", "tdan_judge.c")]
        # -ffp-contract=off as in the firmware: the same cells on every compiler.
        subprocess.run([cc, "-O2", "-std=c11", "-ffp-contract=off", "-I", os.path.join(ANALYSIS, "include"),
                        "-I", os.path.join(ANALYSIS, "src"), main] + src + ["-lm", "-o", tool], check=True)
        white = cells_of(tool, read_photo(args.dir, "blanco.raw565", "white.png"), h)
        grey = cells_of(tool, read_photo(args.dir, "gris.raw565", "grey.png"), h)
    with open(args.output, "w") as f:
        f.write(format_header(white, grey, args.date))
    print("written", args.output)


# ---- The frames ----

# The camera's answer to each primary, chromaticity measured on the fixture
# (white-relative): red, green and blue sum to a neutral white.
PRIMARY = ((0.9388, 0.0120, 0.0492), (0.0, 1.0, 0.0), (0.0037, 0.1078, 0.8884))
PRIMARY_GAIN = (1.06097, 0.87226, 1.06686)
DARK = 6          # the bezel and the room in a black photo, grey levels
NOISE = 3         # sensor noise: the sum of two uniform 0..NOISE, centred
BLUR = 0.8        # optics, photo px
SUPER = 4         # the panel is drawn this many times larger before the warp


def panel(pattern, dead=()):
    """The panel's own pixels for a pattern: an RGB image PANEL_W x PANEL_H."""
    if pattern in ("black", "nomarks"):
        img = Image.new("RGB", (PANEL_W, PANEL_H), (0, 0, 0))
        if pattern == "black":
            for x, y in MARKS:
                img.paste((255, 255, 255), (x - MARK_HALF, y - MARK_HALF, x + MARK_HALF, y + MARK_HALF))
        return img
    colour = {"white": (255, 255, 255), "grey": (128, 128, 128), "red": (255, 0, 0),
              "green": (0, 255, 0), "blue": (0, 0, 255)}[pattern]
    img = Image.new("RGB", (PANEL_W, PANEL_H), colour)
    for x, y in dead:
        img.putpixel((x, y), (0, 0, 0))
    return img


def camera(img, level):
    """Photograph a panel image: the camera's primaries, the exposure (white reads `level`), the pose, the optics."""
    big = img.resize((PANEL_W * SUPER, PANEL_H * SUPER), Image.NEAREST)
    # Perspective data maps photo -> panel: the inverse of H_NOMINAL, on the enlarged panel.
    a, b, c, d, e, f, g, h, i = H_NOMINAL
    inv = (e * i - f * h, c * h - b * i, b * f - c * e,
           f * g - d * i, a * i - c * g, c * d - a * f,
           d * h - e * g, b * g - a * h, a * e - b * d)
    inv = [v / inv[8] for v in inv]
    data = (inv[0] * SUPER, inv[1] * SUPER, inv[2] * SUPER, inv[3] * SUPER, inv[4] * SUPER, inv[5] * SUPER,
            inv[6], inv[7])
    warped = big.transform((WIN_W, WIN_H), Image.PERSPECTIVE, data, Image.BILINEAR)
    warped = warped.filter(ImageFilter.GaussianBlur(BLUR))
    pr, pg, pb = warped.split()
    rng = random.Random(level)
    src = [pr.tobytes(), pg.tobytes(), pb.tobytes()]
    chans = []
    for k in range(3):
        mix = [PRIMARY[j][k] * PRIMARY_GAIN[j] * level / 255.0 for j in range(3)]
        noise = rng.randbytes(2 * WIN_W * WIN_H)
        vals = bytearray(WIN_W * WIN_H)
        for n in range(WIN_W * WIN_H):
            v = DARK + mix[0] * src[0][n] + mix[1] * src[1][n] + mix[2] * src[2][n]
            v += (noise[2 * n] % (NOISE + 1)) + (noise[2 * n + 1] % (NOISE + 1)) - NOISE
            v = min(255, max(0, int(v + 0.5)))
            vals[n] = v
        chans.append(Image.frombytes("L", (WIN_W, WIN_H), bytes(vals)))
    photo = Image.merge("RGB", chans)
    # What the camera delivers is RGB565: keep exactly those levels.
    return photo.point(
        [((v >> 3) << 3) | (v >> 5) for v in range(256)] +
        [((v >> 2) << 2) | (v >> 6) for v in range(256)] +
        [((v >> 3) << 3) | (v >> 5) for v in range(256)])


# What each frame is: pattern, exposure (the level a white would read), dead pixels.
DEAD_CLUSTER = ((150, 240), (158, 240), (154, 247))
FRAMES = {
    "black": ("black", 255 * 3, ()),
    "white": ("white", 150, ()),
    "grey": ("grey", 253, ()),
    "red": ("red", 130, ()),
    "green": ("green", 130, ()),
    "blue": ("blue", 130, ()),
    "white_dead": ("white", 150, DEAD_CLUSTER),
    "grey_dead": ("grey", 253, DEAD_CLUSTER),
    "black_nomarks": ("nomarks", 255 * 3, ()),
}


def cmd_frames(args):
    os.makedirs(args.dir, exist_ok=True)
    for name, (pattern, level, dead) in FRAMES.items():
        camera(panel(pattern, dead), level).save(os.path.join(args.dir, name + ".png"), optimize=True)
        print("written", name)
    with open(os.path.join(args.dir, "H.txt"), "w") as f:
        f.write(" ".join(repr(v) for v in H_NOMINAL) + "\n")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    h = sub.add_parser("header", help="tdan_gold.h from the golden photos")
    h.add_argument("dir")
    h.add_argument("-o", "--output", default=HEADER)
    h.add_argument("--date", default="(date not given)")
    f = sub.add_parser("frames", help="the host suite's frames")
    f.add_argument("dir")
    args = p.parse_args()
    if args.cmd == "header":
        cmd_header(args)
    else:
        cmd_frames(args)


if __name__ == "__main__":
    main()
